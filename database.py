"""Conexões transacionais para SQLite local e PostgreSQL externo."""

import os
import sqlite3
from contextlib import contextmanager
from pathlib import Path
from urllib.parse import parse_qs, urlsplit


class Database:
    def __init__(self, connection, postgres=False):
        self.connection = connection
        self.postgres = postgres

    def execute(self, sql, params=()):
        # Only application-owned SQL uses '?' placeholders; values stay bound.
        if self.postgres:
            sql = sql.replace("?", "%s")
        return self.connection.execute(sql, params)

    def executemany(self, sql, params):
        if self.postgres:
            with self.connection.cursor() as cursor:
                cursor.executemany(sql.replace("?", "%s"), params)
        else:
            self.connection.executemany(sql, params)

    def lock_expense_order(self, user_id):
        if self.postgres:
            self.execute("SELECT id FROM users WHERE id = ? FOR UPDATE", (user_id,))
        else:
            self.execute("BEGIN IMMEDIATE")


def database_url():
    url = os.environ.get("DATABASE_URL", "").strip()
    if "DATABASE_URL" in os.environ and not url:
        raise RuntimeError("DATABASE_URL está vazia; configure a conexão PostgreSQL.")
    if not url and os.environ.get("VERCEL"):
        raise RuntimeError("DATABASE_URL é obrigatória na Vercel; SQLite local não é permitido.")
    if url:
        parts = urlsplit(url)
        if parts.scheme not in {"postgres", "postgresql"} or not parts.hostname or not parts.path.strip("/"):
            raise RuntimeError("DATABASE_URL deve ser uma URL PostgreSQL com host e banco.")
        sslmode = parse_qs(parts.query).get("sslmode", ["require"])[-1]
        if os.environ.get("VERCEL") and sslmode not in {"require", "verify-ca", "verify-full"}:
            raise RuntimeError("A conexão PostgreSQL na Vercel deve exigir TLS (sslmode=require ou verify-full).")
    return url


@contextmanager
def connect(sqlite_path):
    url = database_url()
    if url:
        try:
            import psycopg
            from psycopg.rows import dict_row
        except ImportError:
            raise RuntimeError("Instale requirements.txt para usar PostgreSQL.") from None
        # Disable prepared statements for compatibility with transaction poolers.
        connection = psycopg.connect(
            url, row_factory=dict_row, connect_timeout=10, prepare_threshold=None,
            **({} if "sslmode" in parse_qs(urlsplit(url).query) else {"sslmode": "require"}),
        )
    else:
        connection = sqlite3.connect(sqlite_path, timeout=10)
        connection.row_factory = sqlite3.Row
        connection.execute("PRAGMA foreign_keys = ON")
    try:
        yield Database(connection, postgres=bool(url))
        connection.commit()
    except BaseException:
        connection.rollback()
        raise
    finally:
        connection.close()


def init_db(sqlite_path):
    if not database_url():
        Path(sqlite_path).parent.mkdir(parents=True, exist_ok=True)
    with connect(sqlite_path) as db:
        if db.postgres:
            # Serialize concurrent schema initialization across processes.
            db.execute("SELECT pg_advisory_xact_lock(20261031)")
        identity = "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if db.postgres else "INTEGER PRIMARY KEY"
        statements = [
            f"""CREATE TABLE IF NOT EXISTS users (
                id {identity}, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL, created_at TEXT NOT NULL
            )""",
            """CREATE TABLE IF NOT EXISTS sessions (
                token_hash TEXT PRIMARY KEY,
                user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                expires_at TEXT NOT NULL
            )""",
            f"""CREATE TABLE IF NOT EXISTS expenses (
                id {identity},
                user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                description TEXT NOT NULL, kind TEXT NOT NULL, account TEXT NOT NULL,
                amount_cents INTEGER NOT NULL CHECK(amount_cents > 0),
                due_date TEXT NOT NULL, created_at TEXT NOT NULL,
                sort_order INTEGER,
                is_paid INTEGER NOT NULL DEFAULT 0 CHECK(is_paid IN (0, 1))
            )""",
            "CREATE INDEX IF NOT EXISTS expenses_user_date ON expenses(user_id, due_date)",
            f"""CREATE TABLE IF NOT EXISTS recurring_expenses (
                id {identity},
                user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                description TEXT NOT NULL, kind TEXT NOT NULL, account TEXT NOT NULL,
                amount_cents INTEGER NOT NULL CHECK(amount_cents > 0),
                first_due_date TEXT NOT NULL,
                is_active INTEGER NOT NULL DEFAULT 1 CHECK(is_active IN (0, 1)),
                created_at TEXT NOT NULL
            )""",
            """CREATE TABLE IF NOT EXISTS recurring_occurrences (
                recurring_id INTEGER NOT NULL REFERENCES recurring_expenses(id) ON DELETE CASCADE,
                month TEXT NOT NULL,
                PRIMARY KEY (recurring_id, month)
            )""",
            "CREATE INDEX IF NOT EXISTS recurring_user ON recurring_expenses(user_id)",
        ]
        for statement in statements:
            db.execute(statement)
        if not db.postgres:
            columns = {row["name"] for row in db.execute("PRAGMA table_info(expenses)")}
            if "sort_order" not in columns:
                db.execute("ALTER TABLE expenses ADD COLUMN sort_order INTEGER")
            if "is_paid" not in columns:
                db.execute("ALTER TABLE expenses ADD COLUMN is_paid INTEGER NOT NULL DEFAULT 0 CHECK(is_paid IN (0, 1))")


if __name__ == "__main__":
    init_db(Path(os.environ.get("FINANCE_DB", Path(__file__).parent / "data" / "finance.db")))
    print("Estrutura do banco inicializada.")
